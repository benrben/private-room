"""Build a fine-tuning dataset for Arcelle's agents.

    cd sidecar
    uv run python devtools/dataset/build.py corpus            # questions  -> data/_corpus/
    uv run python devtools/dataset/build.py record --agent X  # trajectories -> data/X.jsonl
    uv run python devtools/dataset/build.py check             # the quality gate

Why this is generated by driving the REAL graphs
------------------------------------------------
The system prompt, the tool schemas and the message shapes all have to match
what the model sees at inference or the fine-tune trains a format that never
occurs. Rather than hand-writing that, `record` runs each question through the
agent's own compiled graph against a scripted room bridge and captures what
actually happened. Teacher output comes from whatever `--teacher` names — a
strong cloud model by default, so this is distillation.

THE HAZARD THIS FILE EXISTS TO AVOID
------------------------------------
Nine of the twelve workers have their FIRST tool call fired by the GRAPH, not
the model: `media.transcribe` gets `stt_status` free, `app.ui` gets
`ui_snapshot` free, the `recall_act_check` agents get their index call free, and
`chain_stage`/`route_act` have their catalog narrowed to one verb before the
model is asked anything.

In the transcript those synthesized calls are INDISTINGUISHABLE from model
choices — an assistant message carrying `tool_calls`, exactly like any other
(verified: `media.transcribe` produces `assistant(stt_status)` at index 2). So
training naively on raw transcripts teaches the model to emit the very calls the
graph already makes for it. At inference it would emit them again, hit duplicate
suppression, and burn the round the shape was built to save — a fine-tune that
actively fights the architecture, showing up as "the model got worse after
training" with no obvious cause.

So a trajectory is split into one record per MODEL DECISION, and the completion
of every record is a turn the model itself produced. Graph-fired calls stay in
the prompt as context (which is exactly where they are at inference) and are
never a training target.
"""

