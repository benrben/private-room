#: ONE coherent fixture room, answered consistently by every tool.
#:
#: This table is the single highest-leverage thing in the file, and getting it
#: wrong is silent. The bridge answers any unlisted tool with "OK.", the teacher
#: correctly notices it learned nothing, and writes an honest "I tried to remove
#: the connector but the tools aren't responding". Train on a few thousand of
#: those and you have distilled LEARNED HELPLESSNESS — a model whose answer to
#: "delete the workflow" is to explain that it can't. Measured 2026-07-26: with
#: 13 of 51 tools fixtured, 8 of 12 sampled trajectories ended in an apology.
#:
#: So: every tool in the catalog gets a plausible RESULT, and they all describe
#: the same room — the same five files, the same one skill, the same two
#: connectors — because a teacher that reads `lease.pdf` in one call and a
#: different file list in the next writes answers full of hedging.
#:
#: A value may be a plain string OR a callable taking the call's arguments. The
#: callables are not decoration: a fixture that answers "tidy.py finished" to
#: `run_script(name="invoice.py")` is an ARGUMENT-BLIND fixture, and the teacher
#: notices — "I asked to run invoice.py but the result came back for tidy.py"
#: (measured 2026-07-26, 2 of 3 scripts.run trajectories). Training on that
#: teaches a student that arguments are decorative.


