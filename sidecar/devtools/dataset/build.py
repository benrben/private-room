def check(paths: list[Path]) -> int:
    bad = 0
    for p in sorted(paths):
        rows, qs, short, shapes = 0, set(), 0, {}
        dupes = 0
        for n, line in enumerate(p.open(encoding="utf-8"), 1):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError as e:
                print(f"{p.name}:{n}  BAD JSON — {e}")
                bad += 1
                continue
            rows += 1
            if "messages" in rec:
                ms = rec["messages"]
                user = next((m["content"] for m in ms if m["role"] == "user"), "")
                final = ms[-1]
                ans = final.get("content") or ""
                shape = "tool_call" if final.get("tool_calls") else "text"
            else:
                user, ans, shape = rec.get("question", ""), rec.get("answer", ""), "text"
            k = user.strip().lower()
            if k in qs:
                dupes += 1
            qs.add(k)
            if shape == "text" and len(ans) < 150:
                short += 1
            h = hashlib.md5(
                (ans[:40] + str(sorted(shapes))[:0]).encode()
            ).hexdigest()[:6]
            shapes[shape] = shapes.get(shape, 0) + 1
            del h
        ok = rows >= 2000 and dupes == 0 and short == 0
        print(
            f"{p.name:<26} rows={rows:<6} uniq_q={len(qs):<6} dupes={dupes:<5} "
            f"short_answers={short:<5} shapes={shapes}  {'OK' if ok else 'NEEDS WORK'}"
        )
        if not ok:
            bad += 1
    return bad


