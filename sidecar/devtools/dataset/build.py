#: The four datasets. Grouping is a WRITE-TIME routing decision only — every
#: record still carries its own `agent`, so these can be re-cut later without
#: re-recording anything.
#:
#: Grouped rather than per-agent because ten of the fourteen agents cannot
#: honestly reach the brief's 2,000-row floor: there are not 2,000 distinct ways
#: to ask for a skill, and padding one intent with more phrasings teaches the
#: format instead of the task. Every group below clears the floor on real,
#: distinct intents.
GROUPS: dict[str, tuple[str, ...]] = {
    "knowledge": ("chat.answer", "chat.web", "chat.browse", "files.read"),
    "automation": ("jobs.run", "jobs.workflows", "scripts.run"),
    "extend": ("skills.use", "skills.author", "connectors.admin", "connectors.use"),
    "media_app": (
        "media.transcribe",
        "media.video",
        "creator.studio",
        "creator.draw",
        "app.ui",
    ),
}

CATALOG_PATH = Path(__file__).resolve().parent / "tool_catalog.json"


def group_of(agent: str) -> str:
    for name, members in GROUPS.items():
        if agent in members:
            return name
    return "other"


def load_catalog() -> dict[str, dict]:
    """The REAL tool catalog — descriptions and JSON schemas straight from Rust.

    Generated by the `tool_catalog_snapshot_is_current` test in `room_mcp.rs`,
    which is also what keeps it honest: change a tool's schema and that test
    fails until the snapshot is regenerated.

    Before this existed the builder invented `"<name> — see the room tool
    catalog."` with `parameters: {}`, which meant the teacher picked tools from
    bare names and every training row carried empty schemas — so a fine-tune
    learned tool NAMES but nothing about their arguments, and the `tools` block
    in the data did not match the one at inference.
    """
    if not CATALOG_PATH.exists():  # pragma: no cover - dev-time guard
        raise SystemExit(
            f"missing {CATALOG_PATH}\n"
            "regenerate it: cd src-tauri && "
            "UPDATE_TOOL_SNAPSHOT=1 cargo test --lib tool_catalog_snapshot"
        )
    return {t["name"]: t for t in json.loads(CATALOG_PATH.read_text(encoding="utf-8"))}


def fixture_reply(name: str, args: dict) -> str:
    """What the scripted room answers for one tool call.

    A tool with no entry is a BUG, not a default. The old `REPLIES.get(n, "OK.")`
    meant adding a tool to an agent's box silently degraded the dataset instead
    of failing, which is how 38 of 51 tools came to be unfixtured without anyone
    noticing. Loud is cheap here: the recorder catches it, prints the name and
    skips that one question.
    """
    if name not in REPLIES:
        # A name the catalog HAS but this table lacks is a bug in this file, and
        # staying loud about it is what stopped 38 unfixtured tools going
        # unnoticed. A name the catalog does NOT have is something else: the
        # model invented a tool. Real rooms answer that with an MCP error, and
        # the recovery it provokes is worth training on — so mirror the room
        # rather than throwing the whole trajectory away. (qwen invents
        # `read_file`, which is not an Arcelle tool; Sonnet never did.)
        if name in load_catalog():
            raise KeyError(f"no fixture reply for tool {name!r} — add one to REPLIES")
        return f"Error: no such tool {name!r} in this room."
    reply = REPLIES[name]
    return reply(args) if callable(reply) else reply


def _openai_tools(specs: list[dict]) -> list[dict]:
    """The brief's tool shape: flat name/description/parameters."""
    out = []
    for s in specs:
        fn = s.get("function") or s
        out.append(
            {
                "name": fn.get("name", ""),
                "description": fn.get("description", ""),
                "parameters": fn.get("parameters", {}) or {},
            }
        )
    return out


def split_records(
    state: dict, tools: list[dict], agent: str, mode: str = "answers"
) -> list[dict]:
    """One record per MODEL decision. See the module docstring.

    A record's completion is always the LAST message, and it is always a turn
    the model produced. Graph-fired assistant turns remain in the prompt — which
    is exactly where they sit at inference — but never become a target.
    """
    msgs = state.get("messages", [])
    synthesized: set[int] = set(state.get("synth_turns", ()))
    records = []
    # ONE record per question by default. A trajectory naturally yields several
    # (each tool choice, then the answer) and they all share the same user turn —
    # so emitting them together puts the same question in both train and test
    # once the splitter dedupes on it. That is textbook leakage and it inflates
    # the score of whatever you compare next. `--mode all` opts back in for a
    # trainer that groups by question before splitting.
    if mode == "answers":
        final = (state.get("final_text") or "").strip()
        if not final:
            return []
        return [
            {
                "messages": [dict(x) for x in msgs]
                + [{"role": "assistant", "content": final}],
                "tools": tools,
                "agent": agent,
            }
        ]
    for i, m in enumerate(msgs):
        if m.get("role") != "assistant" or i in synthesized:
            continue
        prompt = [dict(x) for x in msgs[:i]]
        target = dict(m)
        if not (target.get("content") or "").strip() and not target.get("tool_calls"):
            continue
        records.append({"messages": prompt + [target], "tools": tools, "agent": agent})

    # The FINAL ANSWER is the most valuable record and it is NOT in `messages`:
    # `synthesize` settles it into `final_text` instead, so a splitter that only
    # walked the transcript would emit tool-selection examples and no answers at
    # all — and the brief's "no answer under 150 chars" gate would then fail on a
    # dataset that simply never contained an answer.
    final = (state.get("final_text") or "").strip()
    if final:
        records.append(
            {
                "messages": [dict(x) for x in msgs] + [{"role": "assistant", "content": final}],
                "tools": tools,
                "agent": agent,
            }
        )
    return records


#: Failures worth waiting out rather than discarding the question for. A run
#: spanning days on a subscription WILL be rate-limited; treating that the same
#: as a bad answer would silently shed thousands of questions and leave a
#: dataset whose gaps correlate with time of day rather than with difficulty.
_TRANSIENT = (
    "rate limit",
    "rate_limit",
    "429",
    "overloaded",
    "529",
    "timed out",
    "usage limit",
    "connection",
    "temporarily",
    # HTTP transport, which a 32-wide API run hits routinely and a
    # subprocess-per-call one never did. "Server disconnected without sending a
    # response" contains none of the words above, so it was being treated as a
    # bad answer and burning the question instead of waiting a moment.
    "disconnected",
    "remoteprotocol",
    "readtimeout",
    "connecterror",
    "read timeout",
    "timeout",
    "502",
    "503",
    "504",
    "bad gateway",
    "service unavailable",
    "internal server error",
    # OpenRouter routes to an upstream provider that can fail on its own; the
    # gateway reports it as this, which names none of the words above.
    "provider returned",
    "no completion",
)


def is_transient(err: str) -> bool:
    low = err.lower()
    return any(s in low for s in _TRANSIENT)


def already_recorded(out_path: Path) -> set[str]:
    """The questions this file already answers, so a resumed run skips them."""
    done: set[str] = set()
    if not out_path.exists():
        return done
    for line in out_path.open(encoding="utf-8"):
        try:
            rec = json.loads(line)
        except json.JSONDecodeError:
            continue
        u = next(
            (m["content"] for m in rec.get("messages", []) if m["role"] == "user"), ""
        )
        done.add(u.strip().lower())
    return done


def interleave(queues: dict[str, list[str]]) -> list[tuple[str, str]]:
    """Round-robin the per-agent queues into ONE work list.

    Draining agents one after another is the obvious shape and the wrong one for
    a run measured in days: interrupt it at 30% and you have four finished
    agents and nine empty files — nothing you can train on. Interleaved, the
    same interruption leaves ~30% of every agent, which is a usable dataset.
    The order within an agent is preserved, so resume stays deterministic.
    """
    out: list[tuple[str, str]] = []
    for i in range(max((len(v) for v in queues.values()), default=0)):
        for agent, qs in queues.items():
            if i < len(qs):
                out.append((agent, qs[i]))
    return out


async def record_agents(
    queues: dict[str, list[str]],
    out_paths: dict[str, Path],
    concurrency: int = 8,
    mode: str = "answers",
    retries: int = 4,
) -> dict[str, dict]:
    """Record trajectories CONCURRENTLY across every agent at once.

    Each trajectory is an independent graph run with its own bridge, and a cloud
    CLI teacher is a SUBPROCESS per call — not one resident model — so nothing
    serialises it the way `Lane::LocalLlm` serialises Ollama. The pool is global
    rather than per-agent so it stays saturated: a narrow agent running dry no
    longer idles slots waiting for the next agent to start.

    Appends rather than truncates, and skips questions already present, so a run
    that dies at hour six resumes instead of starting over.
    """
    from e2e_live.harness import RecordingBridge, run_worker_live

    from arcelle_sidecar.agents import (
        ALL_REGISTRY_TOOLS,
        agent_tool_specs,
        get_agent,
        toolbox_for,
    )

    catalog = load_catalog()
    served: dict[str, list] = {}
    schemas: dict[str, list] = {}
    stats: dict[str, dict] = {}
    todo: dict[str, list[str]] = {}

    # Several agents share one output file (the four groups), so handles and the
    # already-recorded set are keyed by PATH, not by agent. Keying them by agent
    # would open the same file four times and let the same question be recorded
    # once per agent — exactly the duplicate the brief says leaks across the
    # train/test split.
    paths = {p.resolve() for p in out_paths.values()}
    handles: dict[Path, Any] = {p: p.open("a", encoding="utf-8") for p in paths}
    done_by_path: dict[Path, set[str]] = {p: already_recorded(p) for p in paths}
    claimed: dict[Path, set[str]] = {p: set() for p in paths}

    for agent, questions in queues.items():
        box = sorted(toolbox_for(agent, set(ALL_REGISTRY_TOOLS)))
        missing = [n for n in box if n not in catalog]
        if missing:  # pragma: no cover - dev-time guard
            raise SystemExit(f"{agent}: not in the tool snapshot: {missing}")
        # The teacher sees the tools EXACTLY as the room serves them, and the
        # record carries the same specs — so the `tools` block in the data is
        # the one the student meets at inference.
        served[agent] = [dict(catalog[n]) for n in box]
        if get_agent(agent).main:
            # The MAIN agent never holds a room tool. `prepare` replaces its
            # catalog with the ask_*_agent specialists, so recording its box
            # would have written eighteen room tools into rows whose model only
            # ever saw six delegation tools — the exact prompt/inference
            # mismatch this file exists to prevent. The bridge still serves the
            # room catalog, because that is what decides which specialists are
            # reachable.
            offered = agent_tool_specs(web_enabled=True, served_names=set(box))
        else:
            offered = [
                {
                    "function": {
                        "name": n,
                        "description": catalog[n].get("description", ""),
                        "parameters": catalog[n].get("inputSchema", {}) or {},
                    }
                }
                for n in box
            ]
        schemas[agent] = _openai_tools(offered)
        path = out_paths[agent].resolve()
        fresh = []
        for q in questions:
            k = q.strip().lower()
            if k and k not in claimed[path] and k not in done_by_path[path]:
                claimed[path].add(k)
                fresh.append(q)
        todo[agent] = fresh
        stats[agent] = {
            "kept": 0,
            "failed": 0,
            "n": 0,
            "todo": len(fresh),
            "done": len(done_by_path[path]),
            "path": out_paths[agent].name,
        }

    work = interleave(todo)
    sem = asyncio.Semaphore(max(1, concurrency))
    lock = asyncio.Lock()
    progress = {"n": 0}

    async def attempt(agent: str, q: str) -> list[dict] | None:
        """One trajectory, retrying only what waiting can fix."""
        for i in range(retries + 1):
            bridge = RecordingBridge(
                tools=served[agent], reply=fixture_reply
            )
            try:
                out = await run_worker_live(agent, q, bridge=bridge)
                return split_records(out["state"], schemas[agent], agent, mode)
            except Exception as exc:  # noqa: BLE001 - one bad question must not kill a long run
                msg = f"{type(exc).__name__}: {str(exc)[:300]}"
                if i < retries and is_transient(msg):
                    # Backoff is per-task, not global: the semaphore slot is
                    # held while sleeping, so a rate-limited run throttles
                    # itself down instead of hammering the limit in lockstep.
                    delay = 30 * (2**i)
                    print(
                        f"  retry in {delay}s ({i + 1}/{retries}) {q[:32]!r}: {msg[:120]}",
                        file=sys.stderr,
                    )
                    await asyncio.sleep(delay)
                    continue
                # The message, not just the class: a long run that silently
                # sheds every question to `LlmError` is indistinguishable from
                # one shedding a few, and the difference is the whole run.
                print(f"  skip [{agent}] {q[:40]!r}: {msg}", file=sys.stderr)
                return None
            finally:
                bridge.close()
        return None

    # Which model produced each row. A dataset assembled by more than one
    # teacher is only a problem you can REASON about if the rows say who wrote
    # them; without this the two distributions are indistinguishable after the
    # fact and the set can never be re-cut or audited.
    teacher_id = os.environ.get("ARCELLE_E2E_MODEL", "")

    async def one(agent: str, q: str) -> None:
        async with sem:
            recs = await attempt(agent, q)
            async with lock:
                progress["n"] += 1
                if recs is None:
                    stats[agent]["failed"] += 1
                else:
                    fh = handles[out_paths[agent].resolve()]
                    for rec in recs:
                        rec["teacher"] = teacher_id
                        fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    stats[agent]["kept"] += len(recs)
                    stats[agent]["n"] += 1
                if progress["n"] % 25 == 0:
                    for fh in handles.values():
                        fh.flush()
                    kept = sum(s["kept"] for s in stats.values())
                    print(
                        f"  {progress['n']}/{len(work)} trajectories, {kept} records",
                        file=sys.stderr,
                    )

    try:
        await asyncio.gather(*(one(a, q) for a, q in work))
    finally:
        for fh in handles.values():
            fh.close()
    return {
        agent: {
            "agent": agent,
            "file": s["path"],
            "asked": s["todo"],
            "skipped_already_done": s["done"],
            "records": s["kept"],
            "failed": s["failed"],
        }
        for agent, s in stats.items()
    }


def export(min_answer: int = 150) -> dict[str, dict]:
    """Build the deliverable `data/<group>.jsonl` from the raw recordings.

    Applies exactly the brief's gates — one JSON object per line, questions
    deduped, no answer under `min_answer` characters — and reports what each
    one cost, because a gate that silently removes an eighth of the data should
    say so.
    """
    DATA.mkdir(exist_ok=True)
    report: dict[str, dict] = {}
    for group in GROUPS:
        src = RAW / f"{group}.jsonl"
        rows: list[dict] = []
        seen: set[str] = set()
        dropped_short = dropped_dupe = 0
        if src.exists():
            for line in src.open(encoding="utf-8"):
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except json.JSONDecodeError:
                    continue
                msgs = rec.get("messages", [])
                user = next((m["content"] for m in msgs if m["role"] == "user"), "")
                answer = (msgs[-1].get("content") or "").strip() if msgs else ""
                key = user.strip().lower()
                if key in seen:
                    dropped_dupe += 1
                    continue
                # A tool-call target has no prose to measure; the length gate is
                # about answers.
                if not msgs[-1].get("tool_calls") and len(answer) < min_answer:
                    dropped_short += 1
                    continue
                seen.add(key)
                rows.append(rec)
        out = DATA / f"{group}.jsonl"
        with out.open("w", encoding="utf-8") as fh:
            for rec in rows:
                fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
        report[group] = {
            "rows": len(rows),
            "dropped_short": dropped_short,
            "dropped_dupe": dropped_dupe,
        }
    return report


def regroup_legacy(data: Path) -> int:
    """Fold any per-agent `<agent>.jsonl` into its group file, then remove it.

    The layout changed from thirteen files to four after some rows had already
    been recorded; those rows cost real money and each one already names its
    own `agent`, so they are moved rather than re-earned.
    """
    moved = 0
    for p in sorted(data.glob("*.jsonl")):
        if p.stem in GROUPS:
            continue
        rows = [ln for ln in p.read_text(encoding="utf-8").splitlines() if ln.strip()]
        by_group: dict[str, list[str]] = {}
        for ln in rows:
            try:
                agent = json.loads(ln).get("agent", "")
            except json.JSONDecodeError:
                continue
            by_group.setdefault(group_of(agent), []).append(ln)
        for gname, lines in by_group.items():
            with (data / f"{gname}.jsonl").open("a", encoding="utf-8") as fh:
                fh.write("\n".join(lines) + "\n")
            moved += len(lines)
        p.unlink()
        print(f"  folded {p.name} -> {sorted(by_group)} ({len(rows)} rows)", file=sys.stderr)
    return moved


