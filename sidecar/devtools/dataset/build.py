#: Per-agent caps that override `--per-agent`.
#:
#: The four `extend` agents were widened (see `intents`) to lift their group over
#: the 2,000 floor, which would have taken it from 2,076 to 7,330 questions —
#: roughly $1,500 of teacher time for a group that only needed to clear a floor.
#: Clearing it with margin is the goal, not maximising rows: 750 apiece puts the
#: group near 3,000 raw, ~2,600 after the answer-length gate.
CAPS = {
    "skills.use": 750,
    "skills.author": 750,
    "connectors.admin": 750,
    "connectors.use": 750,
}


def build_corpus(target: int, seed: int = 7, existing: Path | None = None) -> dict[str, list[str]]:
    """The question corpus, ADDITIVE: an existing corpus is kept and topped up.

    Regeneration used to be destructive in a way that costs real money. The
    generator produces more candidates than the cap keeps, so re-running it after
    widening one agent's intents re-shuffled which subset survived — 1,962 of
    `files.read`'s 2,500 questions were swapped for different ones. Every swapped
    question is one the recorder has already paid for and one it would now pay
    for again: measured, a plain regenerate turned a $264 top-up into $615.

    So whatever is already on disk stays, in order, and new intents only fill the
    remaining room under the cap. Re-running with no new intents is a no-op.
    """
    from arcelle_sidecar.agents import REGISTRY

    existing = existing if existing is not None else DATA / "_corpus"
    out: dict[str, list[str]] = {}
    for spec in REGISTRY:
        # Seeded PER AGENT. A single shared Random makes each agent's shuffle
        # depend on how many questions the agents before it happened to
        # generate, so widening one agent's intents silently reorders every
        # agent after it in the registry — which is not what "reproducible"
        # should mean for a file you regenerate as the roster grows.
        rng = random.Random(f"{seed}:{spec.id}")
        seen: set[str] = set()
        qs: list[str] = []

        prior = existing / f"{spec.id}.txt"
        if prior.exists():
            for line in prior.read_text(encoding="utf-8").splitlines():
                k = line.strip().lower()
                if k and k not in seen:
                    seen.add(k)
                    qs.append(line)

        fresh: list[str] = []
        for core in intents(spec.id):
            for s in styles(core):
                for mod in MODIFIERS:
                    v = mod.format(q=s)
                    k = v.strip().lower()
                    if k and k not in seen:
                        seen.add(k)
                        fresh.append(v)
        rng.shuffle(fresh)

        cap = CAPS.get(spec.id, target)
        room = max(0, cap - len(qs)) if cap else len(fresh)
        out[spec.id] = qs + fresh[:room]
    return out


