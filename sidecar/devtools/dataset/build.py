def _a(args: dict, *keys: str, default: str = "it") -> str:
    """First present argument among `keys`, for echoing back into a result."""
    for k in keys:
        v = args.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
        if v not in (None, "", [], {}):
            return str(v)
    return default


