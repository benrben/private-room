def styles(core: str) -> list[str]:
    """One intent, many surfaces. This is what stops the model learning a
    template: the SHAPE of the input varies, not only its content."""
    bare = core.rstrip("?.")
    return [
        bare,
        bare + "?",
        bare.lower(),
        bare.capitalize() + ".",
        f"hey can you {bare.lower()}",
        f"{bare.lower()} pls",
        f"i need you to {bare.lower()}",
        f"could you {bare.lower()}, thanks",
        f"{bare.lower()}... not sure if you can do that",
        f"quick one — {bare.lower()}",
        f"so {bare.lower()} and then tell me what you found",
        bare.replace("the ", "teh ").replace("you ", "yuo "),
    ]


