/** Runtime array of every valid `invoke()` channel name. */
export const ALL_COMMAND_NAMES: readonly (keyof Commands)[] = Object.keys(
  ALL_COMMANDS_TYPED
) as (keyof Commands)[];

/** Runtime array of every valid `on()` event channel name. */
export const ALL_EVENT_NAMES: readonly (keyof EventPayloads)[] = Object.keys(
  ALL_EVENTS_TYPED
) as (keyof EventPayloads)[];

/** The command list as a `Set`, for O(1) allowlist membership checks. A `Set`,
 * never a plain `{}` lookup object, so an externally-controlled channel string
 * can never be checked with `in` / bracket indexing against something that has
 * a `__proto__`/`constructor` own key. */
export const COMMAND_CHANNEL_SET: ReadonlySet<string> = new Set<string>(ALL_COMMAND_NAMES);

/** The event list as a `Set`, same reasoning as {@link COMMAND_CHANNEL_SET}. */
export const EVENT_CHANNEL_SET: ReadonlySet<string> = new Set<string>(ALL_EVENT_NAMES);

/** Is `channel` a real `Commands` key — i.e. safe to hand to
 * `ipcRenderer.invoke`? A plain `string` parameter on purpose: this is the
 * boundary function a caller hands an UNTRUSTED, renderer-supplied value to. */
export function isKnownCommandChannel(channel: string): channel is keyof Commands {
  return COMMAND_CHANNEL_SET.has(channel);
}

/** Is `channel` a real `EventPayloads` key — i.e. safe to `ipcRenderer.on` /
 * `removeListener` against? Same untrusted-input contract as
 * {@link isKnownCommandChannel}. */
export function isKnownEventChannel(channel: string): channel is keyof EventPayloads {
  return EVENT_CHANNEL_SET.has(channel);
}
