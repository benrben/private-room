/**
 * The compile-checked list of every valid IPC channel name — both directions:
 * `keyof Commands` (`ipc-contract.ts`, renderer→main `invoke()`) and `keyof
 * EventPayloads` (`events.ts`, main→renderer `on()`).
 *
 * ============================================================================
 * WHY AN OBJECT LITERAL, NOT A GENERATED ARRAY
 * ============================================================================
 * TypeScript interface/type keys do not survive compilation — there is no
 * `Object.keys(Commands)` to call at runtime — so SOMETHING has to turn "the
 * keys of a type" into a real array a preload script can check an untrusted
 * string against. The two obvious ways to do that are:
 *
 *   (a) a generator script that regex-scrapes `ipc-contract.ts`/`events.ts`
 *       into a committed array, plus a test that re-scrapes and diffs; or
 *   (b) a `Record<keyof T, true>` OBJECT LITERAL, whose keys are then read off
 *       with `Object.keys` at module load.
 *
 * This file uses (b). `Record<K, true>` on an object literal rejects BOTH a
 * missing key and an excess one, so drift is a COMPILE error in `npm run
 * typecheck` — not a test that has to remember to re-derive, and not a
 * generator someone can forget to re-run. (a) was the other candidate's
 * approach and it works, but its guarantee is only as good as two hand-copied
 * ~10-line regexes staying byte-identical between the generator and its drift
 * test, and it cannot catch anything until the suite runs.
 *
 * ============================================================================
 * WHY ITS OWN FILE, IMPORTING NOTHING BUT TYPES
 * ============================================================================
 * `electron/preload/index.ts` needs this exact list to build its channel
 * allowlist (D10: "reject unknown channels rather than blindly forwarding any
 * string the renderer sends"), and `electron/main/ipc/registry.ts` needs the
 * same list for its completeness diff. `registry.ts` pulls in the whole
 * main-process module graph (`roomManager.ts`,
 * `better-sqlite3-multiple-ciphers`, `sttTools.ts`, …) — native bindings and
 * Node-only code that must never be bundled into a preload script. One shared,
 * dependency-free source of truth is what lets both sides import the SAME list
 * instead of each keeping a copy that can silently diverge.
 */

